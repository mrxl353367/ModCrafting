#!/usr/bin/env node
/**
 * Make a fresh git worktree usable for Core/MCP. Explicit --desktop also restores
 * Electron and the gitignored legacy renderer data.
 *
 * Safe to run repeatedly and cheap when everything is already in place, so it is
 * wired to the Qoder SessionStart hook.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, copyFileSync, mkdirSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const quiet = process.argv.includes('--quiet')
const force = process.argv.includes('--force')
const desktop = process.argv.includes('--desktop')

const log = (...args) => { if (!quiet) console.log('[setup:worktree]', ...args) }

/** Qoder hooks deliver a JSON payload on stdin; fall back to the current directory. */
function readHookCwd() {
  if (process.stdin.isTTY) return null
  try {
    const raw = readFileSync(0, 'utf8').trim()
    if (!raw) return null
    const payload = JSON.parse(raw)
    return typeof payload.cwd === 'string' ? payload.cwd : null
  } catch {
    return null
  }
}

function findRoot(start) {
  let dir = resolve(start || process.cwd())
  for (let i = 0; i < 8; i++) {
    const pkg = join(dir, 'package.json')
    if (existsSync(pkg)) {
      try {
        if (JSON.parse(readFileSync(pkg, 'utf8')).name === 'modcrafting') return dir
      } catch { /* not our package.json */ }
    }
    const parent = dirname(dir)
    if (parent === dir) break
    dir = parent
  }
  return null
}

function run(cmd, args, cwd) {
  // pnpm is a .cmd shim on Windows; all arguments here are fixed by this script.
  const result = spawnSync(cmd, args, { cwd, stdio: quiet ? 'ignore' : 'inherit', shell: cmd === 'pnpm' && process.platform === 'win32', windowsHide: true })
  if (result.error) return { code: -1, error: result.error.message }
  return { code: result.status ?? 1, stderr: result.stderr?.toString() || '' }
}

/** The primary checkout holds the generated data a worktree lacks. */
function primaryCheckout(root) {
  const result = spawnSync('git', ['worktree', 'list', '--porcelain'], { cwd: root, encoding: 'utf8', windowsHide: true })
  if (result.status !== 0) return null
  const paths = result.stdout
    .split('\n')
    .filter((line) => line.startsWith('worktree '))
    .map((line) => line.slice('worktree '.length).trim())
  const other = paths.find((p) => resolve(p) !== resolve(root))
  return other || null
}

function needsInstall(root) {
  const modules = join(root, 'node_modules')
  const lock = join(root, 'pnpm-lock.yaml')
  const installedLock = join(modules, '.pnpm', 'lock.yaml')
  if (!existsSync(lock) || !existsSync(installedLock)) return true
  if (readFileSync(lock, 'utf8') !== readFileSync(installedLock, 'utf8')) return true
  const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  for (const pkg of Object.keys({ ...manifest.dependencies, ...manifest.devDependencies })) {
    if (!existsSync(join(modules, pkg, 'package.json'))) return true
  }
  // pnpm also checks manifest/config drift without fetching or reinstalling.
  return run('pnpm', ['install', '--frozen-lockfile', '--offline', '--lockfile-only', '--ignore-scripts'], root).code !== 0
}

function electronBinary(root) {
  return join(root, 'node_modules', 'electron', 'dist', process.platform === 'win32' ? 'electron.exe' : 'electron')
}

/** Items data is generated by `pnpm run assets:items` (needs Python) and gitignored. */
function ensureItemsData(root) {
  const target = join(root, 'src', 'renderer', 'src', 'data', 'items.ts')
  if (existsSync(target) && !force) return { step: 'items.ts', status: 'ok' }

  const primary = primaryCheckout(root)
  const candidate = primary ? join(primary, 'src', 'renderer', 'src', 'data', 'items.ts') : null
  if (candidate && existsSync(candidate)) {
    mkdirSync(dirname(target), { recursive: true })
    copyFileSync(candidate, target)
    log(`copied generated items.ts from ${primary} (${statSync(target).size} bytes)`)
    return { step: 'items.ts', status: 'copied' }
  }

  const generated = run('pnpm', ['run', 'assets:items'], root)
  if (generated.code === 0 && existsSync(target)) {
    log('generated items.ts via pnpm run assets:items')
    return { step: 'items.ts', status: 'generated' }
  }
  return { step: 'items.ts', status: 'missing', hint: '主 checkout 不可用且 assets:items 失败，请手动执行 pnpm run assets:items' }
}

function main() {
  const root = findRoot(readHookCwd())
  if (!root) {
    // Not a ModCrafting workspace: nothing to do, and never fail a session over it.
    process.exit(0)
  }

  const results = []

  if (needsInstall(root) || force) {
    log(`installing dependencies (pnpm install --frozen-lockfile${desktop ? '' : ' --ignore-scripts'})…`)
    const installed = run('pnpm', ['install', '--frozen-lockfile', ...(desktop ? [] : ['--ignore-scripts'])], root)
    results.push({ step: 'pnpm install', status: installed.code === 0 ? 'ok' : `failed(${installed.code})` })
    if (installed.code !== 0) process.exit(1)
  } else {
    results.push({ step: 'pnpm install', status: 'skipped' })
  }

  if (desktop && !existsSync(electronBinary(root))) {
    log('restoring Electron binary from local cache…')
    const fixed = run('node', ['node_modules/electron/install.js'], root)
    results.push({ step: 'electron binary', status: fixed.code === 0 && existsSync(electronBinary(root)) ? 'ok' : `failed(${fixed.code || 'still missing'})` })
  } else if (desktop) {
    results.push({ step: 'electron binary', status: 'ok' })
  }

  if (desktop) results.push(ensureItemsData(root))
  const native = run(process.execPath, ['scripts/lib/ensure-native-deps.mjs', ...(desktop ? ['--desktop'] : [])], root)
  results.push({ step: desktop ? 'Desktop native dependencies' : 'esbuild', status: native.code === 0 ? 'ok' : `failed(${native.code})` })

  const failed = results.filter((entry) => String(entry.status).startsWith('failed') || entry.status === 'missing')
  if (!quiet) {
    for (const entry of results) console.log(`[setup:worktree]   ${entry.step}: ${entry.status}${entry.hint ? ` — ${entry.hint}` : ''}`)
  }
  if (failed.length > 0) {
    console.error(`[setup:worktree] ${failed.length} step(s) incomplete: ${failed.map((f) => f.step).join(', ')}`)
    process.exit(1)
  }
  process.exit(0)
}

main()
